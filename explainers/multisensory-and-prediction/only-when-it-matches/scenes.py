def spikes(x=-5.5,y=-1.7,w=11,color=ORANGE,mode='baseline',h=.5):
    # Illustrative integrate-and-fire event generator. Identical baseline drive in
    # active/passive strips; only the turn-window modulation differs. Not data.
    dt=.001; ts=np.arange(0,1,dt)
    base=16+3*np.sin(2*np.pi*7*ts)+2*np.sin(2*np.pi*13*ts)
    drive=base.copy()
    if mode=='quiet': drive=4+np.sin(2*np.pi*5*ts)
    if mode=='active': drive+=2*((ts>.35)&(ts<.75))
    if mode=='passive': drive+=36*((ts>.35)&(ts<.75))
    if mode=='steps': drive=5+90*sum(np.exp(-((ts-c)/.045)**2) for c in [.17,.43,.69,.88])
    if mode=='burst': drive=5+95*((ts>.52)&(ts<.85))
    phase=0.; events=[]; rng=np.random.default_rng(41); threshold=rng.uniform(.5,1.5)
    for t,r in zip(ts,drive):
        phase+=r*dt
        if phase>=threshold:
            events.append(t);phase-=threshold;threshold=rng.uniform(.5,1.5)
    return VGroup(Line([x,y,0],[x+w,y,0],color=GREY),*[Line([x+w*t,y,0],[x+w*t,y+h,0],color=color,stroke_width=2) for t in events])


def meter(x,y,level=None,dashed=False,w=2.1,h=.4,color=YELLOW,ends=True,stack=False):
    box=Rectangle(width=w,height=h,color=GREY,stroke_width=2).move_to([x,y,0])
    if dashed: box=DashedVMobject(box,num_dashes=18)
    g=VGroup(box)
    if level is None: g.add(label('?',x,y,26,GREY))
    elif stack:
        for start,length,c in [(0,.1,GREY),(.1,.9,YELLOW)]:
            g.add(Rectangle(width=(w-.1)*length,height=h-.1,stroke_width=0,fill_color=c,fill_opacity=.85).move_to([x-w/2+.05+(w-.1)*(start+length/2),y,0]))
    else:
        g.add(Rectangle(width=(w-.1)*level,height=h-.1,stroke_width=0,fill_color=color,fill_opacity=.85).move_to([x-w/2+.05+(w-.1)*level/2,y,0]))
    if ends:g.add(label('low',x-w/2,y-.43,26,GREY),label('high',x+w/2,y-.43,26,GREY))
    return g


def table(rows=2,third='unknown',question=False,status=False):
    g=VGroup(label('Motion-related modulation · ordinal schematic',y=3.25,size=28),
        label('Canal afferents',-.65,2.55,28),label('Central neurons',2.55,2.55,28))
    names=['Active turn','Passive turn','Active + added\npassive motion']
    if status:g.add(label('Feedback',5.25,2.55,28))
    g.icons=[];g.central=[];g.rowgroups=[]
    for i in range(rows):
        y=1.55-i*1.65
        icon=turn_icon(i).move_to([-5.65,y,0]);g.icons.append(icon)
        if i==2:icon[2].set_color(YELLOW)
        row=VGroup(icon,label(names[i],-3.25,y,26),meter(-.65,y,None if i==2 else .9,dashed=i==2,ends=i!=2),
                   meter(2.55,y,.15 if i==0 else (.9 if i==1 or third=='total' else None),stack=i==2 and third=='total'))
        g.central.append(row[-1])
        if i<2:row.add(spikes(1.5,y-.98,2.1,TEXT,'active' if i==0 else 'passive',.22))
        else:row.add(label('expected,\nnot recorded',-.65,y-.62,22,GREY))
        if status and i!=1:
            row.add(label('✓ matches\nsuppressed' if i==0 else '× mismatch\nsuppression\nfails',5.25,y,26,GREEN if i==0 else RED))
        g.add(row);g.rowgroups.append(row)
    legend=VGroup(T('● motor command · blue motor: external turn',size=22,color=GREY))
    if third=='total':
        legend.add(T('  Total:',size=22),T('active',size=22,color=GREY),T('+ passive',size=22,color=YELLOW))
    legend.arrange(RIGHT,buff=.12).move_to([0,-2.82,0]);g.add(legend)
    if question:g.add(label('Predict: what do the central neurons report?',y=-3.25,size=28,color=YELLOW))
    return g


