def robot_stage(delay=False,question=False):
    # Arms end at wrists; robot tips meet the lower edge of each palm.
    left_arm=VMobject(color=ORANGE,stroke_width=7).set_points_as_corners([[-1.15,-.45,0],[-2.1,-.2,0],[-2.66,.65,0]])
    body=VGroup(RoundedRectangle(width=2.3,height=1.4,corner_radius=.3,color=GREY).move_to([0,-.9,0]),Circle(.45,color=GREY).move_to([0,.25,0]),
        VMobject(color=ORANGE,stroke_width=7).set_points_as_corners([[1.15,-.45,0],[2.1,-.2,0],[2.66,.65,0]]),left_arm)
    contact=[3.5,.125,0]
    a=robot(-3.8,[-3.5,.125,0]);b=robot(3.8,contact)
    h1=palm().scale(.75,about_point=ORIGIN).rotate(PI/2,about_point=ORIGIN).shift([-3.5,.65,0]);h2=palm().scale(.75,about_point=ORIGIN).rotate(-PI/2,about_point=ORIGIN).shift([3.5,.65,0])
    spark=VGroup(*[Line(np.array(contact)+.19*np.array([np.cos(t),np.sin(t),0]),np.array(contact)+.38*np.array([np.cos(t),np.sin(t),0]),color=YELLOW,stroke_width=4) for t in np.linspace(0,TAU,8,endpoint=False)])
    g=VGroup(body,a,b,h1,h2,label('Hand movement',-3.5,2.5,28),label('Touch to other palm',3.5,2.5,28),spark)
    if delay:
        g.add(Arrow([-2.3,1.3,0],[2.3,1.3,0],color=ORANGE,buff=0),
            VGroup(Circle(.4,color=YELLOW,fill_color=BG,fill_opacity=1),Line(ORIGIN,UP*.28,color=YELLOW),Line(ORIGIN,RIGHT*.24,color=YELLOW)).move_to([0,1.3,0]),label('movement → delay → touch',0,1.95,26,YELLOW))
    if question:g.add(label('Predict: what happens to the tickle?',y=3.25,size=30,color=YELLOW),label('Ticklishness (rated)',y=-2.12,size=28),meter(0,-2.75,None,w=4.5),label('Think…',5,-2.65,30,YELLOW))
    return g


