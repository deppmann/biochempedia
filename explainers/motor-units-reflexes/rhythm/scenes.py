def P(x,y): return np.array([x,y,0.])
def poly(pts,color=BLUE,w=5):
    m=VMobject(stroke_color=color,stroke_width=w)
    m.set_points_as_corners([P(*p) for p in pts]); return m

def exc_arrow(a,b,color=GREEN,w=6):
    return Arrow(a,b,buff=0,color=color,stroke_width=w,tip_length=.22)
def inhib_end(a,b,color=RED,w=6):
    a,b=np.array(a,float),np.array(b,float); d=(b-a)/np.linalg.norm(b-a)
    perp=np.array([-d[1],d[0],0])
    return VGroup(Line(a,b,color=color,stroke_width=w),Line(b+perp*.19,b-perp*.19,color=color,stroke_width=w+1))
