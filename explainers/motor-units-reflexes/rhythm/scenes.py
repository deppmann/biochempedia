# The only trace generator. Values are relative 0/1, time in normalized cycles.
def epochs(row,reset=False):
    starts=np.arange(.12+.5*row,3.01,1.)
    if not reset: return [(s,min(s+.30,3.)) for s in starts]
    intervals=[(s,min(s+.30,.80)) for s in starts if s<.76]
    intervals += [(s,min(s+.30,3.)) for s in np.arange(.80+.5*row,3.01,1.)]
    return intervals

def trace(row,x0=-3.25,x1=6.1,y=None,reset=False,dashed=False,end=3,start=0):
    y=(1.1 if row==0 else -2.65) if y is None else y
    events=[]
    val=int(any(a <= start < b for a,b in epochs(row,reset)))
    for a,b in epochs(row,reset):
        if b <= start or a >= end: continue
        if a > start: events.append((a,1))
        events.append((min(b,end),0))
    pts=[(x0+(x1-x0)*start/3,y+1.45*val)]
    for t,on in sorted(events):
        x=x0+(x1-x0)*t/3
        pts.extend([(x,y+1.45*val),(x,y+1.45*on)]); val=on
    pts.append((x0+(x1-x0)*end/3,y+1.45*val))
    line=poly(pts,BLUE,4)
    return DashedVMobject(line,num_dashes=65).set_stroke(color=GREY,opacity=.65) if dashed else line

def trace_panel(recording=False,compact=False):
    x0,x1=(2.35,6.12) if compact else (-3.25,6.12)
    left=.8 if compact else -5.05
    labels=('flexor-\nrelated root','extensor-\nrelated root') if recording else ('ankle flexor\ncontraction','ankle extensor\ncontraction')
    axes=VGroup()
    for y,label in zip((1.1,-2.65),labels):
        axes.add(Line(P(x0,y),P(x1,y),color=GREY,stroke_width=1),T(label,27,BLUE,line_spacing=.8).move_to(P(left,y+.72)))
        tick_x=x1+.3 if compact else x0-.27
        axes.add(T('0',26,GREY).move_to(P(tick_x,y)),T('1',26,GREY).move_to(P(tick_x,y+1.45)))
    axis_y=-2.98
    axes.add(exc_arrow(P(x0,axis_y),P(x1+.12,axis_y),GREY,2))
    for i in range(4):
        x=x0+(x1-x0)*i/3
        axes.add(Line(P(x,axis_y-.08),P(x,axis_y+.08),color=GREY,stroke_width=2),T(str(i),26,GREY).move_to(P(x,axis_y-.27)))
    axes.add(T('time (cycles)',27).move_to(P((x0+x1)/2,-3.70)))
    xa=x0+(x1-x0)*.12/3; xb=xa+(x1-x0)/3
    axes.add(Line(P(xa,2.75),P(xb,2.75),color=TEXT,stroke_width=2),Line(P(xa,2.65),P(xa,2.85),color=TEXT),Line(P(xb,2.65),P(xb,2.85),color=TEXT),T('one cycle',26).move_to(P((xa+xb)/2,3.0)))
    lines=VGroup(*[trace(r,x0,x1) for r in range(2)])
    return axes,lines

