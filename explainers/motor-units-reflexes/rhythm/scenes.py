"""Rhythm Without a Conductor: final-audio visual repair.

COLOR MAP (shared with scenes.old.py): BLUE neurons/axons; GREEN excitation;
RED inhibition/cuts; YELLOW signals/steady drive; TEAL sensory apparatus;
GREY structure/rest; TEXT labels.

The lesson provides qualitative alternation, not digitized recordings or a
quantitative oscillator. All traces are generated by the interval model below:
period = 1 normalized cycle, duty = .30, extensor phase = .5. Sensory reset
advances subsequent epochs by .32 cycles and terminates the ongoing extensor
epoch. Axes explicitly say relative units and cycles, never seconds or mV.
These are labelled schematic. Current bars encode the same on/off state; no
invented physiological amplitudes or waveform wiggles are drawn.
"""
