/* =============================================================================
   The methods library: one entry per experimental method, shared by every course.
   -----------------------------------------------------------------------------
   A method is explained once, here, and shown wherever it is taught. Each entry
   lists the lessons that teach or rely on it (by slug, any course); the lesson
   page reads this file and links its methods under "How we measure it", and
   /methods/<slug>/ shows the film, what the method unlocked, and every lesson
   that uses it. Inventory and decisions: docs/expansion/methods/INVENTORY.md.

   A film is either made for the library (under /explainers/method-<slug>/) or
   reused from a lesson that already explains the method (`from` names that
   lesson, and the film stays where it is). An entry without a film is not
   listed until it has one.
   ============================================================================ */

export type MethodCategory =
  | 'molecules'
  | 'genes'
  | 'cells-imaging'
  | 'physiology'
  | 'organisms-fields'
  | 'data';

export const CATEGORY_LABELS: Record<MethodCategory, string> = {
  molecules: 'Proteins and molecules',
  genes: 'Genes and genomes',
  'cells-imaging': 'Cells and imaging',
  physiology: 'Neurons and physiology',
  'organisms-fields': 'Organisms and the field',
  data: 'Data and inference',
};

export interface MethodFilm {
  src: string;
  captions: string;
  poster: string;
  title: string;
  durationSec: number;
  narration: string;
  /** Set when the film was made for a lesson and is reused here: that lesson's slug. */
  from?: string;
}

export interface Method {
  slug: string;
  name: string;
  aka?: string[];
  category: MethodCategory;
  /** One sentence: the problem the method solves. */
  summary: string;
  film?: MethodFilm;
  /** Lessons that teach or rely on the method, by slug. Order does not matter. */
  lessons: string[];
  /** What the method made possible, shown under the film. Each item is in the film's closing section. */
  unlocked?: { text: string; lesson?: string }[];
  /** Sources for the film's claims beyond the lessons themselves. */
  sources?: { label: string; url?: string }[];
}

const GEMINI = "an AI narrator voice (Gemini, Charon) reading narration written from the method's fact sheet";
